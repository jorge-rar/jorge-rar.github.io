function applyFeedbackButtonLanguage(label, accessibleLabel, href) {
    const button = document.querySelector(".feedback-button");
    if (!button || !feedbackButtonDefaults) return;

    button.innerHTML = label ?? feedbackButtonDefaults.text;
    button.setAttribute("aria-label", accessibleLabel ?? feedbackButtonDefaults.ariaLabel);
    button.setAttribute("title", accessibleLabel ?? feedbackButtonDefaults.title);
    button.setAttribute("href", href ?? feedbackButtonDefaults.href);
}

