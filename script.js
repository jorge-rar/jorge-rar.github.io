function applySkillsLanguage(skillsTranslation) {
    if (!skillsSection || !skillsDefaults) return;

    skillsSection.lang = skillsTranslation ? "de" : "en";
    const title = skillsSection.querySelector("#skills-title");
    if (title) title.innerHTML = skillsTranslation?.title ?? skillsDefaults.title;

    [...skillsSection.querySelectorAll(".skill-row")].forEach((row, rowIndex) => {
        const original = skillsDefaults.rows[rowIndex];
        if (!original) return;

        const heading = row.querySelector("h3");
        if (heading) {
            heading.innerHTML = skillsTranslation?.categories?.[rowIndex] ?? original.title;
        }
        [...row.querySelectorAll(".skill-tags li")].forEach((tag, tagIndex) => {
            tag.innerHTML = skillsTranslation?.tags?.[rowIndex]?.[tagIndex]
                ?? original.tags[tagIndex];
        });
    });
}

