function applyContactLanguage(contactTranslation) {
    if (!contactSection || !contactDefaults) return;

    contactSection.lang = contactTranslation ? "de" : "en";
    const headline = contactSection.querySelector(".contact-message");
    if (headline) {
        headline.innerHTML = contactTranslation
            ? `${contactTranslation.headlineFirstLine}<br><span>${contactTranslation.headlineSecondLine}</span>`
            : contactDefaults.headline;
    }

    const intro = contactSection.querySelector(".contact-content > p");
    if (intro) intro.innerHTML = contactTranslation?.intro ?? contactDefaults.intro;

    const detailLabels = [...contactSection.querySelectorAll(".contact-details-label")];
    if (detailLabels[0]) {
        detailLabels[0].innerHTML = contactTranslation?.contactsLabel ?? contactDefaults.detailLabels[0];
    }
    if (detailLabels[1]) {
        detailLabels[1].innerHTML = contactTranslation?.emailLabel ?? contactDefaults.detailLabels[1];
    }

    const emailButton = contactSection.querySelector(".contact-actions > .button-primary");
    if (emailButton) emailButton.innerHTML = contactTranslation?.emailButton ?? contactDefaults.emailButton;

    const socialLinks = contactSection.querySelector(".contact-social-links");
    if (socialLinks) {
        socialLinks.setAttribute("aria-label", contactTranslation?.socialProfiles ?? contactDefaults.socialLabel);
    }
    [...contactSection.querySelectorAll(".contact-social-link")].forEach((link, index) => {
        link.setAttribute(
            "aria-label",
            contactTranslation?.[index === 0 ? "linkedin" : "github"] ?? contactDefaults.socialLinks[index]
        );
    });

    const signature = contactSection.querySelector(".contact-signoff-signature");
    if (signature) {
        signature.setAttribute("alt", contactTranslation?.signatureAlt ?? contactDefaults.signatureAlt);
    }
}

