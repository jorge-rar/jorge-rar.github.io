function applyExperienceLanguage(experienceTranslation) {
    if (!experienceSection || !experienceDefaults) return;

    experienceSection.lang = experienceTranslation ? "de" : "en";
    const title = experienceSection.querySelector("#experience-title");
    if (title) title.innerHTML = experienceTranslation?.title ?? experienceDefaults.title;

    const entries = [...experienceSection.querySelectorAll(".experience-item")];
    entries.forEach((entry, index) => {
        const original = experienceDefaults.entries[index];
        if (!original) return;

        const translationKey = ["physical", "study", "bosch", "bysteel", "ficosa"][index];
        const translated = experienceTranslation?.[translationKey];
        const titleElement = entry.querySelector("h3");
        const roleElement = entry.querySelector(".experience-role");
        const summaryElement = entry.querySelector(".experience-summary");
        const responsibilityItems = [...entry.querySelectorAll(".experience-responsibilities li")];
        const tagList = entry.querySelector(".experience-tags");
        const tagItems = [...entry.querySelectorAll(".experience-tags li")];
        const toggle = entry.querySelector("[data-responsibility-toggle]");
        const documentLink = entry.querySelector(".document-link");

        if (titleElement) titleElement.innerHTML = translated?.title ?? original.title;
        if (roleElement) roleElement.innerHTML = translated?.role ?? original.role;
        if (summaryElement) summaryElement.innerHTML = translated?.summary ?? original.summary;
        responsibilityItems.forEach((item, itemIndex) => {
            item.innerHTML = translated?.responsibilities?.[itemIndex] ?? original.responsibilities[itemIndex];
        });
        tagItems.forEach((item, itemIndex) => {
            item.innerHTML = translated?.tags?.[itemIndex] ?? original.tags[itemIndex];
        });
        if (tagList) {
            tagList.setAttribute(
                "aria-label",
                translated?.tagsLabel
                    ?? experienceTranslation?.tagsLabels?.[translationKey]
                    ?? original.tagsLabel
            );
        }
        if (toggle) {
            const expanded = toggle.getAttribute("aria-expanded") === "true";
            const template = expanded
                ? experienceTranslation?.hideResponsibilities
                : experienceTranslation?.showResponsibilities;
            const roleName = toggle.dataset.role;
            const label = template
                ? template.replace("{role}", roleName)
                : original.toggleLabel;
            if (label) {
                toggle.setAttribute("aria-label", label);
                toggle.title = label;
            }
        }
        if (documentLink) {
            documentLink.innerHTML = experienceTranslation?.recommendationLetter ?? original.documentLabel;
            if (experienceTranslation?.recommendationLetter) {
                documentLink.setAttribute("aria-label", "Bosch-Empfehlungsschreiben als PDF öffnen");
            } else if (original.documentAriaLabel) {
                documentLink.setAttribute("aria-label", original.documentAriaLabel);
            }
        }
    });
}

const reducedMotionPreference =
    window.matchMedia("(prefers-reduced-motion: reduce)");

let roleIndex = 0;
let characterIndex = 0;
let deleting = false;
let roleTimer = null;
let animationPaused = false;

const typingSpeed = 55;
const deletingSpeed = 32;
const pauseAfterTyping = 1800;
const pauseAfterDeleting = 500;

function updateRoleToggleLanguage() {
    if (!roleToggle) return;

    const translation = siteTranslations[currentLanguage];
    const label = reducedMotionPreference.matches
        ? translation.disabledRole
        : animationPaused
            ? translation.resumeRole
            : translation.pauseRole;

    roleToggle.setAttribute("aria-label", label);
    roleToggle.title = label;
}

function setLanguage(language) {
    if (!siteTranslations[language] || language === currentLanguage) return;

    currentLanguage = language;
    const translation = siteTranslations[language];

    try {
        window.localStorage.setItem(languageStorageKey, language);
    } catch (error) {
        // Language switching still works for the current page session.
    }

    if (heroSection) heroSection.lang = language;
    if (aboutSection) aboutSection.lang = language;
    applyExperienceLanguage(translation.experience);
    applySkillsLanguage(translation.skills);
    applyEducationLanguage(translation.education);
    applyCertificationsLanguage(translation.certifications);
    applyContactLanguage(translation.contact);
    applyNavigationLanguage(translation.navigation);
    applyFeedbackButtonLanguage(translation.feedbackButton, translation.feedbackLabel, translation.feedbackUrl);

    const textTargets = {
        "hero-accessible-summary": translation.accessibleSummary,
        "hero-summary": translation.summary,
        "hero-location-text": translation.location,
        "hero-view-experience": translation.viewExperience,
        "hero-get-in-touch": translation.getInTouch,
        "hero-curriculum-label": translation.curriculum,
        "hero-cv-en-label": translation.cvEnglish,
        "hero-cv-de-label": translation.cvGerman,
        "about-title": translation.about.title,
        "about-intro-primary": translation.about.introPrimary,
        "about-intro-secondary": translation.about.introSecondary,
        "about-working-title": translation.about.skillsTitle,
        "about-growth-title": translation.about.growthTitle,
        "about-languages-title": translation.about.languagesTitle,
        "about-language-portuguese": translation.about.languages[0],
        "about-language-english": translation.about.languages[1],
        "about-language-spanish": translation.about.languages[2],
        "about-language-german": translation.about.languages[3],
        "about-language-native": translation.about.native,
        "about-language-note": translation.about.languageNote,
        "about-interests-title": translation.about.interestsTitle,
        "about-interest-explore": translation.about.interestLabels[0],
        "about-interest-activities": translation.about.interestLabels[1],
        "about-interest-unwind": translation.about.interestLabels[2],
        "about-interest-explore-items": translation.about.interests[0],
        "about-interest-activities-items": translation.about.interests[1],
        "about-interest-unwind-items": translation.about.interests[2]
    };

    [
        "about-skill-adaptable",
        "about-skill-proactive",
        "about-skill-collaborative",
        "about-skill-time-management",
        "about-skill-critical-thinking"
    ].forEach((id, index) => {
        textTargets[id] = translation.about.skills[index];
    });

    [
        "about-growth-delegating",
        "about-growth-over-analysis",
        "about-growth-perfectionism"
    ].forEach((id, index) => {
        textTargets[id] = translation.about.growthAreas[index];
    });

    Object.entries(textTargets).forEach(([id, text]) => {
        const element = document.getElementById(id);
        if (element) element.textContent = text;
    });

    const socialLinks = document.getElementById("hero-social-links");
    const linkedinLink = document.getElementById("hero-linkedin-link");
    const githubLink = document.getElementById("hero-github-link");
    const portraitImage = document.getElementById("hero-portrait-image");

    if (socialLinks) socialLinks.setAttribute("aria-label", translation.socialProfiles);
    if (linkedinLink) linkedinLink.setAttribute("aria-label", translation.linkedin);
    if (githubLink) githubLink.setAttribute("aria-label", translation.github);
    if (portraitImage) portraitImage.alt = translation.portrait;

    const languageGroup = document.querySelector(".language-switch");
    if (languageGroup) languageGroup.setAttribute("aria-label", translation.languageGroup);

    languageButtons.forEach((button) => {
        const isCurrent = button.dataset.language === language;
        const buttonLanguage = button.dataset.language;

        button.classList.toggle("is-current", isCurrent);
        button.setAttribute("aria-pressed", String(isCurrent));
        button.setAttribute("aria-label", isCurrent
            ? translation.languageSelected[buttonLanguage]
            : translation.switchLanguage[buttonLanguage]);
    });

    window.clearTimeout(roleTimer);
    roleTimer = null;
    roles = translation.roles;
    roleIndex = 0;
    characterIndex = roles[0].length;
    deleting = false;
    if (typingElement) typingElement.textContent = roles[0];
    updateRoleToggleLanguage();

    if (!reducedMotionPreference.matches && !animationPaused) {
        roleTimer = window.setTimeout(() => {
            roleTimer = null;
            deleting = true;
            typeRole();
        }, pauseAfterTyping);
    }
}

languageButtons.forEach((button) => {
    button.addEventListener("click", () => {
        setLanguage(button.dataset.language);
    });
});

function typeRole() {
    if (!typingElement) return;

    if (reducedMotionPreference.matches || animationPaused) return;

    const currentRole = roles[roleIndex];

    if (!deleting) {
        typingElement.textContent = currentRole.substring(0, characterIndex + 1);
        characterIndex++;

        if (characterIndex === currentRole.length) {
            roleTimer = window.setTimeout(() => {
                roleTimer = null;
                deleting = true;
                typeRole();
            }, pauseAfterTyping);
            return;
        }

        roleTimer = window.setTimeout(typeRole, typingSpeed);
        return;
    }

    typingElement.textContent = currentRole.substring(0, characterIndex - 1);
    characterIndex--;

    if (characterIndex === 0) {
        deleting = false;
        roleIndex = (roleIndex + 1) % roles.length;
        roleTimer = window.setTimeout(typeRole, pauseAfterDeleting);
        return;
    }

    roleTimer = window.setTimeout(typeRole, deletingSpeed);
}

function handleReducedMotionChange(event) {
    if (!typingElement) return;

    window.clearTimeout(roleTimer);
    roleTimer = null;
    roleIndex = 0;
    characterIndex = 0;
    deleting = false;
    animationPaused = false;
    typingElement.textContent = roles[roleIndex];

    if (roleToggle) {
        roleToggle.disabled = event.matches;
        roleToggle.setAttribute("aria-pressed", "false");
        updateRoleToggleLanguage();
    }

    if (!event.matches) typeRole();
}

if (typingElement) {
    typingElement.textContent = reducedMotionPreference.matches ? roles[0] : "";
    if (roleToggle) {
        roleToggle.disabled = reducedMotionPreference.matches;
        roleToggle.setAttribute("aria-pressed", "false");
        updateRoleToggleLanguage();
    }
    if (!reducedMotionPreference.matches) typeRole();
}

if (roleToggle) {
    roleToggle.addEventListener("click", () => {
        if (reducedMotionPreference.matches) return;

        animationPaused = !animationPaused;
        window.clearTimeout(roleTimer);
        roleTimer = null;
        roleToggle.setAttribute("aria-pressed", String(animationPaused));
        updateRoleToggleLanguage();

        if (!animationPaused) {
            if (!deleting && characterIndex === roles[roleIndex].length) {
                roleTimer = window.setTimeout(() => {
                    roleTimer = null;
                    deleting = true;
                    typeRole();
                }, pauseAfterTyping);
            } else {
                typeRole();
            }
        }
    });
}

if (savedLanguage !== currentLanguage) {
    setLanguage(savedLanguage);
}

if (typeof reducedMotionPreference.addEventListener === 'function') {
    reducedMotionPreference.addEventListener("change", handleReducedMotionChange);
} else {
    reducedMotionPreference.addListener(handleReducedMotionChange);
}

