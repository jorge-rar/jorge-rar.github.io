function applyEducationLanguage(educationTranslation) {
    if (!educationSection || !educationDefaults) return;

    educationSection.lang = educationTranslation ? "de" : "en";
    const title = educationSection.querySelector("#education-title");
    if (title) title.innerHTML = educationTranslation?.title ?? educationDefaults.title;

    [...educationSection.querySelectorAll(".education-item")].forEach((entry, index) => {
        const original = educationDefaults.entries[index];
        const translated = educationTranslation?.entries?.[index];
        if (!original) return;

        const titleElement = entry.querySelector(".education-main h3");
        const fieldElement = entry.querySelector(".education-field");
        const institutionElement = entry.querySelector(".education-institution");
        const detailElement = entry.querySelector(".education-detail");
        const tagList = entry.querySelector(".education-tags");
        const diplomaLink = entry.querySelector(".document-link");

        if (titleElement) titleElement.innerHTML = translated?.title ?? original.title;
        if (fieldElement) fieldElement.innerHTML = translated?.field ?? original.field;
        if (institutionElement) institutionElement.innerHTML = original.institution;
        if (detailElement) detailElement.innerHTML = translated?.detail ?? original.detail;
        if (tagList) {
            tagList.setAttribute("aria-label", translated?.tagsLabel ?? original.tagsLabel);
        }
        [...entry.querySelectorAll(".education-tags li")].forEach((tag, tagIndex) => {
            tag.innerHTML = translated?.tags?.[tagIndex] ?? original.tags[tagIndex];
        });
        if (diplomaLink) {
            diplomaLink.innerHTML = translated?.diplomaLabel ?? original.diplomaLabel;
            diplomaLink.setAttribute(
                "aria-label",
                translated?.diplomaAriaLabel ?? original.diplomaAriaLabel
            );
        }
    });
}

